/* One-off: pull the latin subsets out of the Google CSS and localise them.
   Run from the repo root: node fonts/_fetch.js  */
const fs = require("fs");
const path = require("path");

const DIR = __dirname;
const src = fs.readFileSync(path.join(DIR, "_src.css"), "utf8");

// Split into @font-face blocks, keep latin / latin-ext only.
const blocks = src.split("@font-face").slice(1);
const out = [];
const downloads = [];

for (const raw of blocks) {
  const block = "@font-face" + raw.split("}")[0] + "}";

  const family = (block.match(/font-family:\s*'([^']+)'/) || [])[1];
  const style = (block.match(/font-style:\s*(\w+)/) || [])[1] || "normal";
  const weight = (block.match(/font-weight:\s*([\d\s.]+)/) || [])[1] || "400";
  const url = (block.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
  const range = (block.match(/unicode-range:\s*([^;]+)/) || [])[1] || "";

  if (!family || !url) continue;

  // Latin blocks contain U+0000-00FF; latin-ext contains U+0100.
  const isLatin = /U\+0000-00FF/.test(range);
  const isLatinExt = /U\+0100/.test(range);
  if (!isLatin && !isLatinExt) continue;

  const slug =
    family.toLowerCase().replace(/\s+/g, "-") +
    "-" +
    weight.trim().replace(/\s+/g, "-") +
    (style === "italic" ? "-italic" : "") +
    (isLatinExt ? "-ext" : "") +
    ".woff2";

  downloads.push({ url, file: path.join(DIR, slug) });

  out.push(
    `@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight.trim()};
  font-display: swap;
  src: url('${slug}') format('woff2');
  unicode-range: ${range.trim()};
}`
  );
}

(async () => {
  for (const d of downloads) {
    const res = await fetch(d.url);
    if (!res.ok) throw new Error(`${res.status} for ${d.url}`);
    fs.writeFileSync(d.file, Buffer.from(await res.arrayBuffer()));
    console.log("saved", path.basename(d.file), fs.statSync(d.file).size, "bytes");
  }

  fs.writeFileSync(
    path.join(DIR, "fonts.css"),
    `/* Packaged locally so the app never calls out to Google's servers.\n` +
      `   Generated by fonts/_fetch.js from the Google Fonts CSS API.\n` +
      `   Quicksand, Victor Mono and Monofett are all SIL Open Font License 1.1. */\n\n` +
      out.join("\n\n") +
      "\n"
  );
  console.log("\nwrote fonts.css with", out.length, "@font-face blocks");
})();
